CREATE TABLE IF NOT EXISTS mart.feature_snapshot_run (
    snapshot_version VARCHAR PRIMARY KEY,
    canonical_transform_version VARCHAR NOT NULL,
    star_transform_version VARCHAR NOT NULL,
    policy_version VARCHAR NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    status VARCHAR NOT NULL,
    row_count BIGINT NOT NULL DEFAULT 0,
    race_count BIGINT NOT NULL DEFAULT 0,
    positive_count BIGINT NOT NULL DEFAULT 0,
    no_horse_history_count BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS mart.feature_snapshot_place (
    snapshot_id VARCHAR PRIMARY KEY,
    snapshot_version VARCHAR NOT NULL,
    race_id VARCHAR NOT NULL,
    horse_id VARCHAR NOT NULL,
    race_date DATE NOT NULL,
    feature_as_of DATE NOT NULL,

    meet_code INTEGER NOT NULL,
    race_grade VARCHAR NOT NULL,
    distance_m INTEGER NOT NULL,
    registered_runner_count INTEGER NOT NULL,
    gate_no INTEGER NOT NULL,
    horse_sex VARCHAR NOT NULL,
    horse_age INTEGER,
    carried_weight DECIMAL(8, 2),
    rating INTEGER,

    horse_prior_start_count INTEGER NOT NULL,
    horse_prior_finish_count INTEGER NOT NULL,
    horse_prior_finish_rate DOUBLE,
    horse_prior_plc_hit_count INTEGER NOT NULL,
    horse_prior_plc_hit_rate DOUBLE,
    horse_prior_avg_finish_rank DOUBLE,
    horse_days_since_last_start INTEGER,
    horse_history_available BOOLEAN NOT NULL,
    horse_recent5_start_count INTEGER NOT NULL,
    horse_recent5_finish_rate DOUBLE,
    horse_recent5_plc_hit_rate DOUBLE,
    horse_recent5_avg_finish_rank DOUBLE,
    horse_same_distance_start_count INTEGER NOT NULL,
    horse_same_distance_plc_hit_rate DOUBLE,

    jockey_prior_start_count INTEGER,
    jockey_prior_plc_hit_rate DOUBLE,
    jockey_history_available BOOLEAN NOT NULL,
    trainer_prior_start_count INTEGER,
    trainer_prior_plc_hit_rate DOUBLE,
    trainer_history_available BOOLEAN NOT NULL,

    jockey_id VARCHAR,
    trainer_id VARCHAR,
    source_batch_id VARCHAR NOT NULL,
    policy_version VARCHAR NOT NULL,
    history_window_start_date DATE NOT NULL,
    source_max_event_date DATE,
    history_complete BOOLEAN NOT NULL,
    population_proxy VARCHAR NOT NULL,
    place_hit BOOLEAN NOT NULL,
    result_status VARCHAR NOT NULL,
    is_valid_start BOOLEAN NOT NULL,
    is_valid_finish BOOLEAN NOT NULL,
    population_exclusion_reason VARCHAR,
    created_at TIMESTAMPTZ NOT NULL,

    UNIQUE (snapshot_version, race_id, horse_id)
);
